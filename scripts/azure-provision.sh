#!/usr/bin/env bash
set -euo pipefail

# azure-provision.sh — PBL6-51 one-time (idempotent) Azure VM setup for docker-compose.prod.yml.
#
# Usage: scripts/azure-provision.sh [--dry-run] [-h]
#
# Env (all optional unless noted):
#   AZURE_SUBSCRIPTION_ID     target subscription (az account set equivalent)
#   AZURE_RESOURCE_GROUP      default rg-jobplatform
#   AZURE_VM_NAME             default vm-jobplatform
#   AZURE_LOCATION            default southeastasia  (Azure for Students restricts regions: check below)
#   AZURE_VM_SIZE             default Standard_B2ms  (2 vCPU / 8 GB)
#   AZURE_OS_DISK_GB          default 64 (StandardSSD_LRS)
#   AZURE_VM_SSH_USER         default azureuser
#   AZURE_SSH_PUBKEY          path to public key (default ~/.ssh/id_ed25519.pub; generated by az if missing)
#   AZURE_ADMIN_CIDR          CIDR allowed to SSH (e.g. 203.0.113.7/32). Default * (open — set it!)
#   AZURE_DNS_LABEL           default <vm-name>-<8 hex of subscription/rg hash>  -> <label>.<location>.cloudapp.azure.com
#   AZURE_AUTOSHUTDOWN_TIME   UTC HHMM, default 1500 (= 22:00 Vietnam, UTC+7) — cost safety net
#   AZURE_OPEN_GATEWAY        1 (default) opens gateway port GATEWAY_PORT (5000); 0 if a reverse proxy fronts it
#
# Before running, check what the student subscription allows:
#   az vm list-skus -l <region> --size Standard_B2 --resource-type virtualMachines -o table   # empty/Restricted = not allowed
#   az vm list-usage -l <region> -o table | grep -i -E 'Total Regional|Standard B'            # vCPU quota
#   az account list-locations -o table                                                         # policy may further limit regions

DRY_RUN=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    -h|--help) sed -n '4,28p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "[provision] unknown argument: $arg (see --help)" >&2; exit 2 ;;
  esac
done

log() { printf '[provision] %s\n' "$*"; }
die() { printf '[provision] ERROR: %s\n' "$*" >&2; exit 1; }
run() { if [ "$DRY_RUN" -eq 1 ]; then printf '[dry-run] %s\n' "$*"; else "$@"; fi; }

RG="${AZURE_RESOURCE_GROUP:-rg-jobplatform}"
VM="${AZURE_VM_NAME:-vm-jobplatform}"
LOC="${AZURE_LOCATION:-southeastasia}"
SIZE="${AZURE_VM_SIZE:-Standard_B2ms}"
DISK="${AZURE_OS_DISK_GB:-64}"
USER_NAME="${AZURE_VM_SSH_USER:-azureuser}"
PUBKEY="${AZURE_SSH_PUBKEY:-$HOME/.ssh/id_ed25519.pub}"
ADMIN_CIDR="${AZURE_ADMIN_CIDR:-*}"
SHUTDOWN="${AZURE_AUTOSHUTDOWN_TIME:-1500}"
OPEN_GW="${AZURE_OPEN_GATEWAY:-1}"
GW_PORT="${GATEWAY_PORT:-5000}"
NSG="nsg-$VM"
SUB=()
[ -z "${AZURE_SUBSCRIPTION_ID:-}" ] || SUB=(--subscription "$AZURE_SUBSCRIPTION_ID")

case "$VM" in *[!a-zA-Z0-9-]*) die "AZURE_VM_NAME must be alphanumeric/dash" ;; esac
[ "$DRY_RUN" -eq 1 ] || command -v az >/dev/null 2>&1 || die "az CLI not found (https://aka.ms/installazurecli, then az login)"
[ "$ADMIN_CIDR" != "*" ] || log "WARNING: AZURE_ADMIN_CIDR not set — SSH (22) open to the internet"

if [ -n "${AZURE_DNS_LABEL:-}" ]; then
  LABEL="$AZURE_DNS_LABEL"
else
  LABEL="$(printf '%s' "${AZURE_SUBSCRIPTION_ID:-default}-$RG-$VM" | cksum | cut -d' ' -f1)"
  LABEL="$(printf '%s-%s' "$VM" "$LABEL" | tr '[:upper:]' '[:lower:]')"
fi

# cloud-init: Docker Engine + compose plugin, deploy user in docker group.
CLOUD_INIT="$(mktemp)"
trap 'rm -f "$CLOUD_INIT"' EXIT
cat > "$CLOUD_INIT" <<CI
#cloud-config
package_update: true
packages: [ca-certificates, curl, rsync, git]
runcmd:
  - install -m 0755 -d /etc/apt/keyrings
  - curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  - chmod a+r /etc/apt/keyrings/docker.asc
  - echo "deb [arch=\$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu \$(. /etc/os-release && echo \$VERSION_CODENAME) stable" > /etc/apt/sources.list.d/docker.list
  - apt-get update
  - apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  - usermod -aG docker $USER_NAME
  - sysctl -w vm.max_map_count=262144
  - echo 'vm.max_map_count=262144' > /etc/sysctl.d/99-elasticsearch.conf
  - systemctl enable --now docker
CI

exists() { [ "$DRY_RUN" -eq 0 ] && "$@" >/dev/null 2>&1; }

log "plan: rg=$RG vm=$VM size=$SIZE loc=$LOC disk=${DISK}GB dns=$LABEL.$LOC.cloudapp.azure.com autoshutdown=${SHUTDOWN}UTC"

run az group create -n "$RG" -l "$LOC" "${SUB[@]}" -o none   # idempotent upsert

if exists az network nsg show -g "$RG" -n "$NSG" "${SUB[@]}"; then
  log "nsg $NSG exists — ensuring rules"
else
  run az network nsg create -g "$RG" -n "$NSG" -l "$LOC" "${SUB[@]}" -o none
fi
rule() { # name priority port source
  run az network nsg rule create -g "$RG" --nsg-name "$NSG" -n "$1" --priority "$2" --access Allow --protocol Tcp \
    --direction Inbound --source-address-prefixes "$4" --destination-port-ranges "$3" "${SUB[@]}" -o none
}
rule allow-ssh 100 22 "$ADMIN_CIDR"
rule allow-http 110 80 "*"
rule allow-https 120 443 "*"
[ "$OPEN_GW" != 1 ] || rule allow-gateway 130 "$GW_PORT" "*"

if exists az vm show -g "$RG" -n "$VM" "${SUB[@]}"; then
  log "vm $VM exists — skipping create"
else
  KEYARGS=(--ssh-key-values "$PUBKEY")
  if [ "$DRY_RUN" -eq 0 ] && [ ! -f "$PUBKEY" ]; then KEYARGS=(--generate-ssh-keys); fi
  run az vm create -g "$RG" -n "$VM" -l "$LOC" --size "$SIZE" --image Ubuntu2404 \
    --admin-username "$USER_NAME" "${KEYARGS[@]}" --authentication-type ssh \
    --os-disk-size-gb "$DISK" --storage-sku StandardSSD_LRS \
    --nsg "$NSG" --public-ip-sku Standard --public-ip-address-dns-name "$LABEL" \
    --custom-data "$CLOUD_INIT" "${SUB[@]}" -o none
fi

# Cost safety net: auto-deallocate every night even if we forget `deploy.sh azure down`.
run az vm auto-shutdown -g "$RG" -n "$VM" --time "$SHUTDOWN" "${SUB[@]}" -o none

FQDN="$LABEL.$LOC.cloudapp.azure.com"
if [ "$DRY_RUN" -eq 0 ]; then
  FQDN="$(az vm show -d -g "$RG" -n "$VM" "${SUB[@]}" --query fqdns -o tsv || true)"; FQDN="${FQDN:-$LABEL.$LOC.cloudapp.azure.com}"
fi
log "FQDN: $FQDN"
log "next: export AZURE_RESOURCE_GROUP=$RG AZURE_VM_NAME=$VM AZURE_VM_SSH_USER=$USER_NAME AZURE_SSH_KEY=<private key>; scripts/deploy.sh azure up"
log "cloud-init installs Docker in ~2-3 min after first boot; then deploy.sh can connect."
